"""PostgreSQL trial schema generation (no live database required)."""

import sqlite3
import sys
from decimal import Decimal
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import db
from scripts.postgres_trial import (
    build_schema_statements,
    convert_row,
    describe_sqlite,
    import_trial,
    ordered_tables,
)


def test_trial_schema_preserves_nine_tables_constraints_and_money_types(tmp_path):
    db.DB_PATH = tmp_path / "nexis.db"
    db.init_db()

    with db.get_connection() as conn:
        tables = describe_sqlite(conn)
        order = ordered_tables(tables)
        statements = build_schema_statements(tables, "nexis_trial_test")

    assert len(tables) == 9
    assert len(statements) == 10  # create schema + nine tables
    assert order.index("users") < order.index("missions")
    assert order.index("missions") < order.index("transactions")
    ddl = "\n".join(statements)
    assert "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl
    assert "NUMERIC" in ddl
    assert "UNIQUE" in ddl
    assert "FOREIGN KEY" in ddl
    assert "DROP " not in ddl
    assert "TRUNCATE " not in ddl


def test_float_values_are_prepared_as_decimal():
    assert convert_row((1, 0.1, "Nexis", None)) == (
        1, Decimal("0.1"), "Nexis", None
    )


def test_trial_rejects_unsafe_destination_and_active_database(tmp_path):
    db.DB_PATH = tmp_path / "nexis_hub.db"
    db.init_db()
    with db.get_connection() as conn:
        tables = describe_sqlite(conn)

    with pytest.raises(ValueError):
        build_schema_statements(tables, "public")

    with pytest.raises(ValueError, match="sauvegarde"):
        import_trial(db.DB_PATH, "nexis_trial_test", "unused")


def test_trial_rejects_unexpected_source_tables(tmp_path):
    db.DB_PATH = tmp_path / "nexis.db"
    db.init_db()
    with db.get_connection() as conn:
        conn.execute("CREATE TABLE unexpected_table (id INTEGER PRIMARY KEY)")
    with db.get_connection() as conn:
        with pytest.raises(ValueError, match="Schéma source inattendu"):
            describe_sqlite(conn)
