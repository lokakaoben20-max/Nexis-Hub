"""Build and optionally load an isolated PostgreSQL trial schema from a SQLite backup.

Default mode prints the SQL schema plan without connecting to PostgreSQL.
--apply writes only a *new* nexis_trial_* schema, inside one transaction.
No existing schema is dropped or replaced. Never use the live SQLite file.
"""

import argparse
import os
import re
import sqlite3
import sys
from collections import defaultdict
from contextlib import closing
from decimal import Decimal
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.preflight_postgres import preflight_sqlite


EXPECTED_TABLES = {
    "users", "providers", "missions", "quotes", "transactions",
    "services", "service_requests", "reviews", "platform_settings",
}
TRIAL_SCHEMA_PATTERN = re.compile(r"nexis_trial_[a-z0-9_]{1,40}\Z")


def ident(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def open_readonly_sqlite(path: Path):
    absolute = Path(path).expanduser().resolve()
    if not absolute.is_file():
        raise FileNotFoundError(f"Sauvegarde SQLite introuvable : {absolute}")
    uri = "file:" + quote(str(absolute), safe="/") + "?mode=ro"
    return sqlite3.connect(uri, uri=True)


def describe_sqlite(conn) -> dict:
    tables = {}
    names = [
        row[0] for row in conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table' "
            "AND name NOT LIKE 'sqlite_%' ORDER BY name"
        )
    ]
    if set(names) != EXPECTED_TABLES:
        raise ValueError(
            "Schéma source inattendu : vérifier les tables avant toute migration"
        )

    for table in names:
        escaped = ident(table)
        cols = conn.execute(f"PRAGMA table_info({escaped})").fetchall()
        fks = conn.execute(f"PRAGMA foreign_key_list({escaped})").fetchall()
        unique_sets = []
        for idx in conn.execute(f"PRAGMA index_list({escaped})").fetchall():
            # idx: sequence, name, unique, origin, partial
            if not idx[2] or idx[3] == "pk":
                continue
            if len(idx) > 4 and idx[4]:
                raise ValueError(f"Index unique partiel non pris en charge : {table}")
            index_columns = [
                item[2] for item in conn.execute(f"PRAGMA index_info({ident(idx[1])})")
            ]
            if not index_columns or any(item is None for item in index_columns):
                raise ValueError(f"Index d'expression non pris en charge : {table}")
            unique_sets.append(tuple(index_columns))
        tables[table] = {
            "columns": cols,
            "foreign_keys": fks,
            "unique_sets": unique_sets,
        }
    return tables


def pg_type(sqlite_type: str) -> str:
    declared = sqlite_type.upper()
    if declared.startswith("INT"):
        return "BIGINT"
    if declared.startswith(("REAL", "FLOA", "DOUB", "NUMERIC", "DECIMAL")):
        return "NUMERIC"
    if declared.startswith(("TEXT", "CHAR", "VARCHAR", "CLOB")):
        return "TEXT"
    if declared.startswith("BLOB"):
        return "BYTEA"
    raise ValueError(f"Type SQLite non pris en charge : {sqlite_type}")


def ordered_tables(tables: dict) -> list[str]:
    pending = {}
    for name, metadata in tables.items():
        dependencies = {fk[2] for fk in metadata["foreign_keys"] if fk[2] != name}
        pending[name] = dependencies
    ordered = []
    while pending:
        ready = sorted(name for name, deps in pending.items() if deps.issubset(ordered))
        if not ready:
            raise ValueError("Dépendances circulaires : migration manuelle nécessaire")
        for name in ready:
            ordered.append(name)
            del pending[name]
    return ordered


def build_schema_statements(tables: dict, schema: str) -> list[str]:
    if not TRIAL_SCHEMA_PATTERN.fullmatch(schema):
        raise ValueError("Le nom du schéma doit commencer par nexis_trial_")
    statements = [f"CREATE SCHEMA {ident(schema)}"]
    for table in ordered_tables(tables):
        info = tables[table]
        definitions = []
        for column in info["columns"]:
            _cid, name, kind, not_null, _default, primary_key = column
            data_type = pg_type(kind)
            if primary_key and data_type == "BIGINT":
                part = f"{ident(name)} BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
            else:
                part = f"{ident(name)} {data_type}"
                if primary_key:
                    part += " PRIMARY KEY"
                elif not_null:
                    part += " NOT NULL"
            definitions.append(part)

        for columns in info["unique_sets"]:
            definitions.append(
                "UNIQUE (" + ", ".join(ident(name) for name in columns) + ")"
            )

        grouped = defaultdict(list)
        for foreign_key in info["foreign_keys"]:
            grouped[foreign_key[0]].append(foreign_key)
        for group in grouped.values():
            group.sort(key=lambda item: item[1])
            referenced_table = group[0][2]
            source_cols = ", ".join(ident(fk[3]) for fk in group)
            target_cols = ", ".join(ident(fk[4]) for fk in group)
            definitions.append(
                f"FOREIGN KEY ({source_cols}) REFERENCES "
                f"{ident(schema)}.{ident(referenced_table)} ({target_cols})"
            )

        statements.append(
            f"CREATE TABLE {ident(schema)}.{ident(table)} (\n    "
            + ",\n    ".join(definitions) + "\n)"
        )
    return statements


def convert_row(row: tuple) -> tuple:
    # SQLite REAL is binary floating point; preserve its decimal string representation.
    return tuple(Decimal(str(value)) if isinstance(value, float) else value for value in row)


def verify_money_totals(sqlite_conn, target, schema: str, tables: dict) -> None:
    """Require exact Decimal totals for all financial columns after import."""
    markers = ("amount", "balance", "commission", "fee", "total", "net_")
    for table, metadata in tables.items():
        for column in metadata["columns"]:
            name, kind = column[1], column[2]
            if pg_type(kind) != "NUMERIC":
                continue
            if not any(marker in name.lower() for marker in markers):
                continue
            source_rows = sqlite_conn.execute(
                f"SELECT {ident(name)} FROM {ident(table)}"
            )
            expected = sum(
                (Decimal(str(row[0])) for row in source_rows if row[0] is not None),
                Decimal("0"),
            )
            target.execute(
                f"SELECT COALESCE(SUM({ident(name)}), 0) "
                f"FROM {ident(schema)}.{ident(table)}"
            )
            actual = target.fetchone()[0]
            if actual != expected:
                raise ValueError(f"Total financier divergent : {table}.{name}")


def import_trial(source: Path, schema: str, dsn: str) -> dict:
    if Path(source).name == "nexis_hub.db":
        raise ValueError("Importer une sauvegarde renommée, jamais la base active")
    if not TRIAL_SCHEMA_PATTERN.fullmatch(schema):
        raise ValueError("Destination réservée aux schémas nexis_trial_*")
    manifest = preflight_sqlite(source)
    if not manifest["ready_for_mapping_review"]:
        raise ValueError("La sauvegarde SQLite contient des incohérences à corriger")

    try:
        import psycopg
    except ImportError as exc:
        raise RuntimeError("Installer psycopg avant la migration d'essai") from exc

    with closing(open_readonly_sqlite(source)) as sqlite_conn:
        sqlite_conn.execute("BEGIN")
        tables = describe_sqlite(sqlite_conn)
        statements = build_schema_statements(tables, schema)
        order = ordered_tables(tables)

        # Psycopg commits only when every import and count verification succeeds.
        # Any error rolls back even the schema creation.
        with psycopg.connect(dsn) as pg_conn:
            with pg_conn.cursor() as target:
                target.execute(
                    "SELECT 1 FROM information_schema.schemata WHERE schema_name = %s",
                    (schema,),
                )
                if target.fetchone():
                    raise ValueError("Schéma cible déjà existant : aucun écrasement autorisé")

                for statement in statements:
                    target.execute(statement)

                counts = {}
                for table in order:
                    column_names = [c[1] for c in tables[table]["columns"]]
                    escaped = ident(table)
                    source_cursor = sqlite_conn.execute(f"SELECT * FROM {escaped}")
                    insert_sql = (
                        f"INSERT INTO {ident(schema)}.{escaped} ("
                        + ", ".join(ident(col) for col in column_names)
                        + ") VALUES ("
                        + ", ".join(["%s"] * len(column_names)) + ")"
                    )
                    expected = 0
                    while True:
                        batch = source_cursor.fetchmany(250)
                        if not batch:
                            break
                        target.executemany(insert_sql, [convert_row(row) for row in batch])
                        expected += len(batch)
                    target.execute(f"SELECT COUNT(*) FROM {ident(schema)}.{escaped}")
                    actual = target.fetchone()[0]
                    if actual != expected or actual != manifest["tables"][table]["rows"]:
                        raise ValueError(f"Comptage divergent pour la table {table}")
                    counts[table] = actual

                    id_cols = [
                        c[1] for c in tables[table]["columns"]
                        if c[5] and pg_type(c[2]) == "BIGINT"
                    ]
                    if id_cols:
                        primary = id_cols[0]
                        target.execute(
                            f"SELECT MAX({ident(primary)}) FROM {ident(schema)}.{escaped}"
                        )
                        maximum = target.fetchone()[0]
                        target.execute(
                            "SELECT pg_get_serial_sequence(%s, %s)",
                            (f"{schema}.{table}", primary),
                        )
                        sequence_name = target.fetchone()[0]
                        if sequence_name:
                            target.execute(
                                "SELECT setval(%s::regclass, %s, %s)",
                                (sequence_name, maximum or 1, maximum is not None),
                            )

                verify_money_totals(sqlite_conn, target, schema, tables)
                # All schema constraints have been active throughout the import.
                # Do not log or expose any row-level personal/financial values.
                sqlite_conn.rollback()
                return {
                    "schema": schema,
                    "tables": counts,
                    "rows_imported": sum(counts.values()),
                    "source_schema_sha256": manifest["schema_sha256"],
                    "verified": True,
                }


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Préparer ou lancer une importation PostgreSQL de répétition"
    )
    parser.add_argument("--source", type=Path, required=True, help="Sauvegarde SQLite, jamais la base active")
    parser.add_argument("--schema", default="nexis_trial_preview")
    parser.add_argument("--apply", action="store_true", help="Écrire dans PostgreSQL (schéma neuf uniquement)")
    args = parser.parse_args()

    source = args.source.expanduser().resolve()
    if source.name == "nexis_hub.db":
        raise SystemExit("Utiliser une sauvegarde renommée, pas la base active")

    manifest = preflight_sqlite(source)
    if not manifest["ready_for_mapping_review"]:
        raise SystemExit("Pré-migration bloquée : intégrité ou clés étrangères")

    if not args.apply:
        with closing(open_readonly_sqlite(source)) as conn:
            sql = build_schema_statements(describe_sqlite(conn), args.schema)
        print("\n\n".join(statement + ";" for statement in sql))
        print(f"\n-- Aperçu uniquement : {manifest['table_count']} tables, aucune écriture.")
        return

    dsn = os.getenv("NEXIS_MIGRATION_PG_DSN")
    if not dsn:
        raise SystemExit("NEXIS_MIGRATION_PG_DSN absent : aucune connexion effectuée")
    result = import_trial(source, args.schema, dsn)
    print(f"Import de répétition vérifié : {result['rows_imported']} lignes dans {result['schema']}")


if __name__ == "__main__":
    main()
